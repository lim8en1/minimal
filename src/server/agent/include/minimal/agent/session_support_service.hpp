#pragma once

// The core-provided support service plugins reach through ServiceRegistry::
// Find(kSessionSupportServiceName) -- the sanctioned pull channel, with CORE as
// the provider (an empty attribution, the same convention core tool
// registrations use). It exists because a plugin that reacts to session
// lifecycle (the LLM session titler is the canonical case) needs exactly three
// things core does not otherwise expose across the plugin ABI:
//
//   1. a SessionReader for the session's transcript (observers get seq ranges,
//      deliberately not content -- SessionReader is the sanctioned read path);
//   2. an LlmProvider to call -- by default the session's OWN, so a title is
//      generated by the model the operator already configured, through the
//      shared ProviderInstanceCache (never a second connection);
//   3. the rename itself, which must land in SQLite AND in a live session's
//      in-memory name AND on the wire as SessionMetadataEvent -- three places
//      no plugin should have to keep consistent.
//
// INTERFACE ONLY, header-only, pure virtual: the concrete implementation lives
// in the server binary (agent/session_support.cpp), and virtual dispatch needs
// no exported symbols -- the same shape every plugin-provided service uses.
// Find returning null means the host does not offer the seam (an embedded or
// test harness); degrade, do not error.

#include <memory>
#include <optional>
#include <string>

#include "minimal/llm/provider.hpp"
#include "minimal/session/session_reader.hpp"

namespace minimal::agent {

// The ServiceRegistry name the implementation is provided under. Typed at the
// edges, named in the middle: this string is the only runtime coupling.
inline constexpr const char* kSessionSupportServiceName = "core.session_support";

// A provider plus the model id a ChatRequest should carry.
struct SessionLlm {
    // Shared, never owned exclusively: provider instances are stateless by
    // contract and shared across sessions through ProviderInstanceCache.
    std::shared_ptr<llm::LlmProvider> provider;
    std::string model;  // ChatRequest::model
};

class SessionSupportService {
public:
    virtual ~SessionSupportService() = default;

    // The session's own provider and the model it is currently running
    // (preset- or /model-resolved). nullopt when the session is unknown, is
    // not backed by a provider, or is mid preset-switch -- a momentary
    // condition a caller degrades on, never an error.
    virtual std::optional<SessionLlm> LlmForSession(const std::string& session_id) = 0;

    // Resolve an explicit "<provider>/<model>" override through providers.json
    // and the shared instance cache. nullopt on a malformed ref, an unknown
    // entry, or a model that does not resolve. Callers that pass a user-
    // configured string must treat nullopt as "skip titling", not "fail".
    virtual std::optional<SessionLlm> ResolveModelRef(const std::string& provider_model) = 0;

    // The session's transcript read side -- the same path GetMessages answers
    // from. Null when the session is unknown. The shared_ptr keeps the reader
    // (and the session that owns it) alive for as long as the caller holds it.
    virtual std::shared_ptr<const session::SessionReader> HistoryFor(
        const std::string& session_id) = 0;

    // Persist the name, update a live session's in-memory name, and emit
    // SessionMetadataEvent to the attached client. False when the session is
    // unknown, the name is empty, or the session was created WITH an explicit
    // name -- a user's choice is never clobbered by a generated title (the
    // same protection the free default-name rule's `name = ''` guard gives it).
    virtual bool RenameSession(const std::string& session_id, const std::string& name) = 0;
};

}  // namespace minimal::agent
